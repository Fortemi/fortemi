#!/usr/bin/env python3
"""Reject Buildx bake and rawjson progress output in CI and build tooling.

GHSA-gwr2-q96m-6682 and GHSA-p54p-jq4x-rc28 affect `buildx bake`:
https://github.com/docker/buildx/security/advisories/

Shell quoting, escapes, YAML folding and Dockerfile JSON form can spell the
same command in many ways, so this check deliberately does not parse. It joins
line continuations and removes quote characters and backslashes, then:

- fails any line containing `rawjson`;
- because `buildx` is used in this tree, fails any line containing the
  substring `bake` (escapes such as `bake\\n` become `baken` and still match),
  unless that exact normalized line is listed in ALLOWED_LINES with a reason.

Every policy input must be UTF-8 text without NUL bytes; anything else (for
example a UTF-16 workflow) fails as an unsupported encoding. The rule is
applied across the whole policy tree, so a command assembled from
a variable defined in another file is still caught. Deliberate obfuscation
(splitting the word across variables, base64, printf escapes) is out of scope:
it is a review matter, not an accidental spelling.
"""

import argparse
import re
import sys
from pathlib import Path


POLICY_DIRECTORIES = (".gitea", "scripts", "build")
# Paths relative to the repository root, each with the reason it may mention
# the prohibited words.
SKIP = {
    "scripts/ci/check-buildx-policy.py": "this policy check",
    "tests/test_check_buildx_policy.py": "the policy check's own fixtures",
}
# (path, normalized line) pairs that mention "bake" in an unrelated sense.
ALLOWED_LINES = {
    ("scripts/ci/verify-bundle-db-secrets.py",
     "errors.append(dockerfile.bundle must not bake postgres_password)"):
        "error text about secrets baked into images",
    ("scripts/ci/verify-bundle-db-secrets.py",
     "errors.append(dockerfile.bundle must not bake a credential-bearing url)"):
        "error text about secrets baked into images",
    ("build/README.md",
     "the bundle image bakes docker/seed-data/fortemi-docs.shard (the in-product support "
     "memory archive) into /app/seed-data so first-boot seeding has a known-good corpus to import."):
        "prose about seed data included in the image",
}
CONTINUATION = re.compile(r"\\\r?\n")
QUOTING = re.compile(r"[\"'`\\]")


def normalize(content: str) -> list[str]:
    text = QUOTING.sub("", CONTINUATION.sub("", content)).lower()
    return [line.strip() for line in text.splitlines()]


def violations(content: str, relative: str = "", buildx_in_tree: bool = True) -> list[tuple[int, str]]:
    errors = []
    for number, line in enumerate(normalize(content), 1):
        if "rawjson" in line:
            errors.append((number, "prohibited rawjson progress output"))
        if buildx_in_tree and "bake" in line and (relative, line) not in ALLOWED_LINES:
            errors.append((number, "prohibited Buildx bake reference"))
    return errors


def policy_files(root: Path):
    for directory in POLICY_DIRECTORIES:
        for path in sorted((root / directory).rglob("*")):
            relative = path.relative_to(root).as_posix()
            if not path.is_file() or relative in SKIP:
                continue
            # Only bytecode generated by test runs is skipped.
            if "__pycache__" in path.parts and path.suffix in {".pyc", ".pyo"}:
                continue
            data = path.read_bytes()
            try:
                # NUL bytes mean UTF-16/32 or binary content that would hide words.
                text = None if b"\x00" in data else data.decode("utf-8")
            except UnicodeDecodeError:
                text = None
            yield relative, text


def verify(root: Path) -> list[str]:
    files = list(policy_files(root))
    errors = [f"{relative}:1: unsupported encoding; policy inputs must be UTF-8 text"
              for relative, text in files if text is None]
    readable = [(relative, text) for relative, text in files if text is not None]
    buildx_in_tree = any("buildx" in "\n".join(normalize(text)) for _, text in readable)
    return errors + [f"{relative}:{line}: {message}"
                     for relative, text in readable
                     for line, message in violations(text, relative, buildx_in_tree)]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("root", nargs="?", type=Path, default=Path("."))
    args = parser.parse_args()
    try:
        errors = verify(args.root)
    except OSError as error:
        print(f"Cannot inspect Buildx policy inputs: {error}", file=sys.stderr)
        return 2
    if errors:
        print("\n".join(errors), file=sys.stderr)
        print("See GHSA-gwr2-q96m-6682 and GHSA-p54p-jq4x-rc28; buildx bake and "
              "rawjson progress are not allowed in CI or build tooling.", file=sys.stderr)
        return 1
    print("Buildx invocation policy passed")
    return 0


if __name__ == "__main__":
    sys.exit(main())
