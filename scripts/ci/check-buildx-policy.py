#!/usr/bin/env python3
"""Reject Buildx bake and rawjson progress output in CI and build tooling.

GHSA-gwr2-q96m-6682 and GHSA-p54p-jq4x-rc28 affect `buildx bake`:
https://github.com/docker/buildx/security/advisories/

Shell quoting, comments, YAML folding and Dockerfile JSON form can all
spell the same command in ways a parser would have to model exactly. This
check deliberately does not parse. After removing quote characters and
backslashes, a file fails if it mentions `buildx` and also contains the word
`bake` anywhere, or if it contains `rawjson` anywhere. A legitimate future
mention must be added to SKIP with a reason.
"""

import argparse
import re
import sys
from pathlib import Path


POLICY_DIRECTORIES = (".gitea", "scripts", "build")
# Paths relative to the repository root, each with the reason it may mention
# the prohibited words.
SKIP = {
    "scripts/ci/check-buildx-policy.py": "this policy check",
    "tests/test_check_buildx_policy.py": "the policy check's own fixtures",
}
GENERATED_SUFFIXES = {".pyc", ".pyo"}
CONTINUATION = re.compile(r"\\\r?\n")
NORMALIZE = re.compile(r"[\"'`\\]")
BAKE = re.compile(r"\bbake\b")


def violations(content: str) -> list[tuple[int, str]]:
    # Join shell continuations first, then drop every quoting character.
    text = NORMALIZE.sub("", CONTINUATION.sub("", content)).lower()
    lines = text.splitlines()
    errors = []
    if "buildx" in text:
        errors += [(number, "prohibited Buildx bake reference")
                   for number, line in enumerate(lines, 1) if BAKE.search(line)]
    errors += [(number, "prohibited rawjson progress output")
               for number, line in enumerate(lines, 1) if "rawjson" in line]
    return sorted(errors)


def verify(root: Path) -> list[str]:
    errors = []
    for directory in POLICY_DIRECTORIES:
        for path in sorted((root / directory).rglob("*")):
            relative = path.relative_to(root).as_posix()
            # Bytecode is generated by test runs, not authored input.
            if not path.is_file() or relative in SKIP or path.suffix in GENERATED_SUFFIXES:
                continue
            for line, message in violations(path.read_text(encoding="utf-8", errors="replace")):
                errors.append(f"{relative}:{line}: {message}")
    return errors


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("root", nargs="?", type=Path, default=Path("."))
    args = parser.parse_args()
    try:
        errors = verify(args.root)
    except OSError as error:
        print(f"Cannot inspect Buildx policy inputs: {error}", file=sys.stderr)
        return 2
    if errors:
        print("\n".join(errors), file=sys.stderr)
        print("See GHSA-gwr2-q96m-6682 and GHSA-p54p-jq4x-rc28; buildx bake and "
              "rawjson progress are not allowed in CI or build tooling.", file=sys.stderr)
        return 1
    print("Buildx invocation policy passed")
    return 0


if __name__ == "__main__":
    sys.exit(main())
