#!/usr/bin/env python3
"""Reject prohibited Buildx invocations in CI and build tooling."""

import argparse
import re
import sys
from pathlib import Path


# GHSA-gwr2-q96m-6682 and GHSA-p54p-jq4x-rc28:
# https://github.com/docker/buildx/security/advisories/
BOUNDARY = r'''[\s'";|&()<>]'''
BUILDX_BAKE = re.compile(
    rf"(?:^|{BOUNDARY})buildx(?=$|{BOUNDARY}).*?{BOUNDARY}bake(?=$|{BOUNDARY})"
)
RAWJSON = re.compile(
    rf'''(?:^|{BOUNDARY})--progress(?:=|\s+)(?:"rawjson"|'rawjson'|rawjson)(?=$|{BOUNDARY})'''
)
# Preserve quoted strings, but discard shell/Python/YAML comments.
QUOTES_OR_COMMENT = re.compile(r'''"(?:\\.|[^"\\])*"|'[^']*'|\#.*''')
SKIP = {"scripts/ci/check-no-buildx-bake.py", "tests/test_check_no_buildx_bake.py"}


def violations(content: str) -> list[tuple[int, str]]:
    # Join shell continuations before checking each logical line.
    lines = re.sub(r"\\\r?\n", "", content).splitlines()
    errors = []
    for number, line in enumerate(lines, 1):
        line = QUOTES_OR_COMMENT.sub(
            lambda match: "" if match[0].startswith("#") else match[0], line
        )
        if BUILDX_BAKE.search(line):
            errors.append((number, "prohibited Buildx bake invocation"))
        if RAWJSON.search(line):
            errors.append((number, "prohibited rawjson progress option"))
    return errors


def verify(root: Path) -> list[str]:
    errors = []
    for directory in (".gitea", "scripts", "build"):
        for path in sorted((root / directory).rglob("*")):
            relative = path.relative_to(root).as_posix()
            # Bytecode caches are generated by the test run, not authored inputs.
            if "__pycache__" in path.parts or path.suffix in {".pyc", ".pyo"}:
                continue
            if path.is_file() and relative not in SKIP:
                for line, message in violations(path.read_text(encoding="utf-8", errors="replace")):
                    errors.append(f"{relative}:{line}: {message}")
    return errors


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("root", nargs="?", type=Path, default=Path("."))
    args = parser.parse_args()
    try:
        errors = verify(args.root)
    except OSError as error:
        print(f"Cannot inspect Buildx policy inputs: {error}", file=sys.stderr)
        return 2
    if errors:
        print("\n".join(errors), file=sys.stderr)
        return 1
    print("Buildx invocation policy passed")
    return 0


if __name__ == "__main__":
    sys.exit(main())
